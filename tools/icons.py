def main(images_dir):
    powers = os.path.join(images_dir, 'powers')
    rest_site = os.path.join(images_dir, 'rest_site')
    os.makedirs(rest_site, exist_ok=True)
    png(f'{powers}/spirits_tipsy_power.png', mug((231, 160, 40, 255), (255, 248, 232, 255), (190, 205, 215, 255)))
    png(f'{powers}/spirits_designated_driver_power.png', mug((110, 190, 245, 255), (210, 236, 255, 255), (190, 205, 215, 255)))
    png(f'{powers}/spirits_drunk_driver_power.png', steering_wheel())
    for name, img in card_power_icons().items():
        png(f'{powers}/spirits_{name}_power.png', img)
    tabs = tab_icons()
    for kind, img in tabs.items():
        png(f'{powers}/spirits_{kind}_tab_power.png', img)
    # Rest site options (SpireRestSiteOption.IconPath): the same stein and shot glass.
    png(f'{rest_site}/spirits_chug.png', tabs['chug'])
    png(f'{rest_site}/spirits_shot.png', tabs['shot'])
    for folder, icons in (('relics', relic_icons()), ('potions', potion_icons())):
        os.makedirs(os.path.join(images_dir, folder), exist_ok=True)
        for name, img in icons.items():
            png(os.path.join(images_dir, folder, f'spirits_{name}.png'), img)
    print('wrote icons to', images_dir)


main(sys.argv[1])
